// This file gathers what the classifier needs to know about each path, with
// one batched git command per question (docs/spec/classification.md), and
// hands every path to classify.Classify. The commands run one after another:
// the caller already runs repositories in parallel under a limit, and a
// repository's own commands in parallel would multiply the git processes
// that limit is meant to bound.

// The header sniff's patterns (docs/spec/classification.md#header-sniff),
// POSIX extended regular expressions that git grep -E matches ignoring case.
// They are source, not policy: the blame cache keys on them
// (docs/spec/cache.md).
//
// A header that marks a file generated either declares it ("DO NOT EDIT",
// "@generated", "<auto-generated>") or describes it ("Code generated by",
// "This file was automatically generated"). A declaration counts anywhere
// near the start of a line. A description counts only as the first words of
// a line's text, because in mid-sentence the same words describe something
// else: "Random numbers are generated by a [Source]" in Go's math/rand. On
// Go's source tree the rules keep all 495 files that follow Go's
// generated-code convention and drop 55 of the 67 others that a plain list
// of markers matched, which were prose, identifiers and generator programs
// that print a header in a string.
const (
	// classifyHeaderGate holds the words every rule's match contains. The
	// sniff asks git for lines that match it --and a rule, so the rules
	// run only on the few lines that hold one. On Go's source tree that
	// took 0.8 s, against 1.8 s for a plain list of markers and 3.2 s for
	// the rules alone (git 2.50.1 on macOS).
	classifyHeaderGate = `generated|do not edit|do not modify`

	// classifyQuotes are the characters that open a string literal.
	classifyQuotes = `"'` + "`"

	// classifyLineStart is where a line's text starts: after at most 32
	// characters of indentation and comment punctuation, the characters of
	// //, #, /*, *, <!--, --, ; and Haskell's {-, which proto-lens opens
	// every module it generates with. A docstring line, which has no comment
	// punctuation, starts there too. Any other punctuation is text, so a
	// generator script's template that writes an rST comment in a string,
	// ".. Note this file is autogenerated by ...", is no description. The
	// "-" stays last in the class, where it is no range.
	classifyLineStart = `^[[:space:]/#*;<!{-]{0,32}`

	// classifyWordEnd ends a marker, so an identifier such as
	// AutogeneratedPos is no description.
	classifyWordEnd = `([^[:alnum:]_]|$)`

	// classifyHeaderDescribed is a description where a line's text starts,
	// optionally after a warning word: "Code generated by",
	// "Autogenerated by", "*** WARNING: this file was generated by",
	// "This file is (mostly) automatically generated", "This is a
	// generated file".
	classifyHeaderDescribed = classifyLineStart +
		`((warning|note|notice|important|caution|attention|do not modify|do not change)[^[:alnum:]]{1,8})?` +
		`(this[[:space:]]+((((entire|whole)[[:space:]]+)?(file|code|class|header|module|program|source|document)` +
		`([[:space:]]+file)?[[:space:]]+((is|was|has[[:space:]]+been)[[:space:]]+)?` +
		`(\(?(mostly|partially|partly|fully|entirely|completely)\)?[[:space:]]+)?)|is[[:space:]]+(an?[[:space:]]+)?)` +
		`((auto|machine)[- ]?|automatically[[:space:]]+)?generated` +
		`|(code|machine)[- ]generated|generated[[:space:]]+by|auto-?generated|auto[[:space:]]+generated` +
		`|automatically[[:space:]]+generated)` + classifyWordEnd

	// classifyHeaderDoNotModify is "DO NOT MODIFY" as a line of its own,
	// such as "// DO NOT MODIFY!" or "Do not modify this file by hand.". In
	// a sentence it is advice: "Do not modify a Record after handing out a
	// copy to it" in Go's log/slog.
	classifyHeaderDoNotModify = classifyLineStart +
		`do not modify([[:space:]]+this[[:space:]]+file)?([[:space:]]+(by[[:space:]]+hand|manually|directly))?` +
		`[^[:alnum:]]{0,8}$`

	// classifyHeaderDeclared is a declaration in a line's first 100
	// characters, unless a quote comes before it: then it is in a string
	// literal, as in a generator program that prints its header, such as
	// fmt.Fprintln(&b, "// Code generated by mkbuiltin.go. DO NOT EDIT.").
	classifyHeaderDeclared = `^[^` + classifyQuotes + `]{0,100}(do not edit|@generated|<auto-?generated)` + classifyWordEnd
)

// classifyHeaderLines is how far into a file the header sniff looks: a
// marker counts only on line 40 or before.
const classifyHeaderLines = 40

// The linguist attributes check-attr reports, in this order, for every path.
const (
	classifyAttrGenerated = "linguist-generated"
	classifyAttrVendored  = "linguist-vendored"
)

// PathAt names a path in the tree of a commit that touched it.
type PathAt struct{ Commit, Path string }

// ClassifyPaths classifies every path in the tree at repo.Head, plus each
// path in touched that Head no longer has, with one batched call per git
// question: ls-tree -l for the paths and sizes at Head, check-attr --source
// for linguist attributes, grep for generated headers, and cat-file
// --batch-check for the sizes of touched paths absent at Head
// (docs/spec/classification.md).
//
// touched lists the paths the history touched, in week and scan runs
// alike: scan needs the paths deleted since too, because durable@1 counts
// the prod lines they added. It holds one entry per path, at the newest
// commit that added lines to it, so the path is in that commit's tree; a
// later entry for the same path is ignored. A touched path that exists at
// Head is classified at Head. The result has one PathClass per distinct
// path, sorted by Path.
//
// Only regular files get a role. A symbolic link or a submodule at Head is
// classified like any path, but as no file, so unless the deny list or
// .gitattributes denies it, it is unclassified: it adds nothing and is
// never blamed, although numstat counts a link's target and a submodule
// bump as a changed line. A path Head no longer has is classified as a
// file: cat-file --batch-check cannot say whether it was a link or a
// submodule, because it has no %(objectmode) (verified on git 2.50.1). A
// touched path whose entry names no valid commit has an unknown size (-1).
//
// In a blobless partial clone the blobs are absent and lazy fetch is off,
// so sizes read as unknown, check-attr finds no .gitattributes and the
// header sniff finds nothing. Nothing depends on that: a partial clone has
// no line facts (docs/spec/discovery.md#clone-health).
func ClassifyPaths(ctx context.Context, git domain.GitRunner, repo domain.Repo, p *policy.Policy, touched []PathAt) ([]domain.PathClass, error) {
	if !classifyObjectID(repo.Head) {
		return nil, fmt.Errorf("classify paths: head %q is not a full commit id", repo.Head)
	}
	head, err := classifyTree(ctx, git, repo)
	if err != nil {
		return nil, err
	}

	// The touched paths Head no longer has, each at its first entry.
	var gone []PathAt
	seen := map[string]bool{}
	for _, t := range touched {
		if t.Path == "" || seen[t.Path] {
			continue
		}
		seen[t.Path] = true
		if _, ok := head.entries[t.Path]; ok {
			continue
		}
		gone = append(gone, t)
	}

	paths := make([]string, 0, len(head.order)+len(gone))
	paths = append(paths, head.order...)
	for _, g := range gone {
		paths = append(paths, g.Path)
	}
	attrs, err := classifyAttributes(ctx, git, repo, paths)
	if err != nil {
		return nil, err
	}
	var hits map[string]bool
	if len(head.order) > 0 {
		if hits, err = classifyHeaders(ctx, git, repo, p, head); err != nil {
			return nil, err
		}
	}
	sizes, err := classifySizes(ctx, git, repo, gone)
	if err != nil {
		return nil, err
	}

	var out []domain.PathClass
	for i, path := range paths {
		in := classify.Input{
			Path:      path,
			Generated: attrs[i].generated,
			Vendored:  attrs[i].vendored,
		}
		if i < len(head.order) {
			e := head.entries[path]
			in.AtHead = true
			in.Size = e.size
			in.NotFile = !e.file
			in.HeaderHit = hits[path]
		} else {
			in.Size = sizes[i-len(head.order)]
		}
		out = append(out, classify.Classify(p, in))
	}
	slices.SortFunc(out, func(a, b domain.PathClass) int { return strings.Compare(a.Path, b.Path) })
	return out, nil
}

// classifyEntry is what the classifier needs to know about one path's tree
// entry.
type classifyEntry struct {
	size int64 // bytes; -1 when git cannot tell, or for a submodule
	file bool  // a regular file, not a symbolic link or a submodule
}

// classifyHead is the tree at Head as the classifier sees it.
type classifyHead struct {
	entries map[string]classifyEntry // every blob and submodule at Head
	order   []string                 // the keys of entries, in ls-tree order
}

// classifyTree lists every path at Head with its size:
//
//	git ls-tree -r -l -z <head>
//
// Each record is "<mode> SP <type> SP <object> SP <size> TAB <path> NUL",
// with the size padded with spaces. Regular files are blobs of mode 100644
// or 100755; a blob of mode 120000 is a symbolic link, whose content is its
// target, and a commit is a submodule, whose size is "-". With -r, ls-tree
// lists no trees. A blob whose size git cannot read prints a size that is
// not a number (BAD in a blobless partial clone, verified on git 2.50.1),
// which is an unknown size.
func classifyTree(ctx context.Context, git domain.GitRunner, repo domain.Repo) (*classifyHead, error) {
	head := &classifyHead{entries: map[string]classifyEntry{}}
	cmd := domain.GitCmd{Dir: repo.Path, Args: []string{"ls-tree", "-r", "-l", "-z", repo.Head}}
	err := git.Stream(ctx, cmd, func(r io.Reader) error {
		s := newScanner(r, scanNUL)
		for s.Scan() {
			meta, path, ok := strings.Cut(s.Text(), "\t")
			fields := strings.Fields(meta)
			if !ok || len(fields) != 4 || path == "" {
				return fmt.Errorf("unreadable ls-tree record %q", s.Text())
			}
			e := classifyEntry{size: -1, file: fields[1] == "blob" && fields[0] != "120000"}
			if fields[1] == "blob" {
				if size, err := strconv.ParseInt(fields[3], 10, 64); err == nil && size >= 0 {
					e.size = size
				}
			}
			if _, dup := head.entries[path]; !dup {
				head.order = append(head.order, path)
			}
			head.entries[path] = e
		}
		return s.Err()
	})
	if err != nil {
		return nil, fmt.Errorf("classify paths: %w", err)
	}
	return head, nil
}

// classifyAttr is one path's linguist attributes as check-attr reports
// them: "unspecified", "unset", "set" or a value.
type classifyAttr struct{ generated, vendored string }

// classifyAttributes reads the linguist attributes of paths at Head, in one
// batched call:
//
//	git check-attr -z --source=<head> --stdin linguist-generated linguist-vendored
//
// Stdin is the paths, NUL-terminated; the output is "path NUL attribute NUL
// info NUL" for each path and attribute, in input order. --source reads
// .gitattributes at Head, so a bare mirror answers (without it every
// attribute reads unspecified there), and a work tree answers for the
// scanned commit rather than whatever is checked out. A pattern matches
// the same way on every machine because the runner's prefix pins
// core.ignoreCase=false: a clone on macOS or Windows sets
// core.ignorecase=true, which lets "*.PY linguist-generated" mark a.py
// (verified on git 2.50.1), while a Linux clone, like GitHub, matches
// case-sensitively. The result is in the order of paths.
//
// An empty value, as in "a.py linguist-generated=", is passed on as set.
// check-attr prints it as an empty info (verified on git 2.50.1), while
// libgit2, which GitHub Linguist reads attributes with, leaves an
// assignment with an empty value set; classify reads an empty info as no
// attribute at all, the zero value of an Input built without attributes.
func classifyAttributes(ctx context.Context, git domain.GitRunner, repo domain.Repo, paths []string) ([]classifyAttr, error) {
	if len(paths) == 0 {
		return nil, nil
	}
	var stdin bytes.Buffer
	for _, p := range paths {
		stdin.WriteString(p)
		stdin.WriteByte(0)
	}
	out := make([]classifyAttr, len(paths))
	cmd := domain.GitCmd{
		Dir:   repo.Path,
		Args:  []string{"check-attr", "-z", "--source=" + repo.Head, "--stdin", classifyAttrGenerated, classifyAttrVendored},
		Stdin: bytes.NewReader(stdin.Bytes()),
	}
	answers := 0 // two per path: linguist-generated, then linguist-vendored
	err := git.Stream(ctx, cmd, func(r io.Reader) error {
		s := newScanner(r, scanNUL)
		for s.Scan() {
			path := s.Text()
			if !s.Scan() {
				break
			}
			name := s.Text()
			if !s.Scan() {
				break
			}
			info := s.Text()
			if info == "" {
				info = "set"
			}
			i, generated := answers/2, answers%2 == 0
			want := classifyAttrVendored
			if generated {
				want = classifyAttrGenerated
			}
			switch {
			case i >= len(paths):
				return fmt.Errorf("check-attr answered for more than the %d paths asked", len(paths))
			case path != paths[i] || name != want:
				return fmt.Errorf("check-attr answered %s for %q where %s for %q was due", name, path, want, paths[i])
			case generated:
				out[i].generated = info
			default:
				out[i].vendored = info
			}
			answers++
		}
		return s.Err()
	})
	if err != nil {
		return nil, fmt.Errorf("classify paths: %w", err)
	}
	if answers != 2*len(paths) {
		return nil, fmt.Errorf("classify paths: check-attr gave %d answers for %d paths, want 2 each", answers, len(paths))
	}
	return out, nil
}

// classifyHeaders runs the header sniff once at Head and returns the paths
// with a generated-file header on line 40 or before:
//
//	git grep --no-color --no-column -n -o -z -a -i -E -m 1 -e <gate> \
//	    --and ( -e <described> -e <do not modify> -e <declared> ) <head> -- <pathspecs>
//
// -m 1 stops at a file's first matching line, the only one that can decide
// the line-40 rule, and -o prints only what matched, which the patterns
// bound, so a minified file's megabyte line never reaches stillhere.
// --no-color and --no-column undo a repository's color.grep and
// grep.column, either of which changes the output; a repo-local
// grep.column=true adds a column field (verified on git 2.50.1). Each
// record is "<head>:<path> NUL <line> NUL <match> LF", one for each match
// on the line. Exit status 1 means no file matched.
//
// -a reads every file as text, so no attribute changes the sniff. -I
// would decide what is binary from the diff attribute, which git grep
// reads from the work tree, not from the scanned commit: a file marked
// -diff or binary would be sniffed in a bare mirror but not in a work tree
// of the same commit, and an uncommitted .gitattributes edit would change
// the result (verified on git 2.50.1). The pathspecs keep binary files out
// in practice.
//
// The sniff reads the files the policy can give a role (classifyPathspecs).
// Reading more would change no class, since classify.Classify reads a
// header only on a path a rule counts, but it would cost time; with no
// file that can get a role it does not run.
func classifyHeaders(ctx context.Context, git domain.GitRunner, repo domain.Repo, p *policy.Policy, head *classifyHead) (map[string]bool, error) {
	hits := map[string]bool{}
	specs, sniff := classifyPathspecs(p, head)
	if !sniff {
		return hits, nil
	}
	args := []string{"grep", "--no-color", "--no-column", "-n", "-o", "-z", "-a", "-i", "-E", "-m", "1",
		"-e", classifyHeaderGate, "--and", "(",
		"-e", classifyHeaderDescribed, "-e", classifyHeaderDoNotModify, "-e", classifyHeaderDeclared,
		")", repo.Head, "--"}
	args = append(args, specs...)
	prefix := repo.Head + ":"
	cmd := domain.GitCmd{Dir: repo.Path, Args: args, OKExit: []int{1}}
	err := git.Stream(ctx, cmd, func(r io.Reader) error {
		s := newScanner(r, classifyGrepRecord)
		for s.Scan() {
			fields := bytes.SplitN(s.Bytes(), []byte{0}, 3)
			if len(fields) != 3 || !bytes.HasPrefix(fields[0], []byte(prefix)) {
				return fmt.Errorf("unreadable grep record %q", s.Bytes())
			}
			line, err := strconv.Atoi(string(fields[1]))
			if err != nil {
				return fmt.Errorf("unreadable grep record %q: %w", s.Bytes(), err)
			}
			if line <= classifyHeaderLines {
				hits[string(fields[0][len(prefix):])] = true
			}
		}
		return s.Err()
	})
	if err != nil {
		return nil, fmt.Errorf("classify paths: %w", err)
	}
	return hits, nil
}

// classifyGrepRecord is a bufio.SplitFunc for the header sniff's output: a
// record is "<head>:<path> NUL <line> NUL <marker> LF", returned without the
// LF. The path may hold a newline, so a record ends at the first newline
// after its second NUL, not at the first newline.
func classifyGrepRecord(data []byte, atEOF bool) (advance int, token []byte, err error) {
	if first := bytes.IndexByte(data, 0); first >= 0 {
		if second := bytes.IndexByte(data[first+1:], 0); second >= 0 {
			rest := first + 1 + second + 1
			if end := bytes.IndexByte(data[rest:], '\n'); end >= 0 {
				return rest + end + 1, data[:rest+end], nil
			}
		}
	}
	if atEOF && len(data) > 0 {
		return 0, nil, fmt.Errorf("grep output ends inside a record: %q", data)
	}
	return 0, nil, nil
}

// classifySniffNamed bounds how many files the header sniff names one by
// one (classifyPathspecs). git matches every path at Head against every
// pathspec, so a long list costs more than reading every file; the
// packaged policy names a repository's requirements files, a handful.
const classifySniffNamed = 256

// classifyPathspecs limits the header sniff to the files at Head that the
// policy can give a role, so the sniff's reach and the role rules are one
// statement: ":(icase)*<ext>" for each extension, matched at any depth and
// ignoring case as classify does, "<name>" and "*/<name>" for each exact
// name, glob characters escaped, and ":(literal)<path>" for each regular
// file that only a path rule gives a role (classify.RoleByRuleAlone), such
// as requirements.txt under the packaged policy. When more files than
// classifySniffNamed need naming, the sniff reads every file (no
// pathspec) instead. sniff is false when no file at Head can get a role:
// then there is nothing to read.
func classifyPathspecs(p *policy.Policy, head *classifyHead) (specs []string, sniff bool) {
	for _, ext := range slices.Sorted(maps.Keys(p.Roles.Extensions)) {
		specs = append(specs, ":(icase)*"+classifyGlobEscape(ext))
	}
	for _, name := range slices.Sorted(maps.Keys(p.Roles.Names)) {
		specs = append(specs, classifyGlobEscape(name), "*/"+classifyGlobEscape(name))
	}
	var named []string
	for _, path := range head.order {
		if head.entries[path].file && classify.RoleByRuleAlone(p, path) {
			named = append(named, ":(literal)"+path)
		}
	}
	switch {
	case len(named) > classifySniffNamed:
		return nil, true
	case len(specs)+len(named) == 0:
		return nil, false
	}
	return append(specs, named...), true
}

// classifyGlobEscape escapes the characters a pathspec reads as a glob.
func classifyGlobEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if strings.ContainsRune(`\*?[`, r) {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// classifySizes reads the size of each touched path Head no longer has, in
// the tree of the commit that touched it, in one batched call:
//
//	git cat-file --batch-check="%(objecttype) %(objectsize)" -Z
//
// Stdin is "<commit>:<path>" for each, NUL-terminated; -Z (git 2.42)
// makes the output NUL-terminated too, which a path holding a newline needs.
// Each answer is "blob <size>", another type, or "<input> missing", in input
// order. Anything but a blob is an unknown size (-1); so is a path whose
// entry names no valid commit, which is not asked, because "<empty>:<path>"
// would read the index.
func classifySizes(ctx context.Context, git domain.GitRunner, repo domain.Repo, gone []PathAt) ([]int64, error) {
	sizes := make([]int64, len(gone))
	var asked []int // indexes into gone
	var stdin bytes.Buffer
	for i, g := range gone {
		sizes[i] = -1
		if !classifyObjectID(g.Commit) || strings.IndexByte(g.Path, 0) >= 0 {
			continue
		}
		asked = append(asked, i)
		stdin.WriteString(g.Commit)
		stdin.WriteByte(':')
		stdin.WriteString(g.Path)
		stdin.WriteByte(0)
	}
	if len(asked) == 0 {
		return sizes, nil
	}
	cmd := domain.GitCmd{
		Dir:   repo.Path,
		Args:  []string{"cat-file", "--batch-check=%(objecttype) %(objectsize)", "-Z"},
		Stdin: bytes.NewReader(stdin.Bytes()),
	}
	n := 0
	err := git.Stream(ctx, cmd, func(r io.Reader) error {
		s := newScanner(r, scanNUL)
		for s.Scan() {
			if n >= len(asked) {
				return fmt.Errorf("cat-file answered for more than the %d objects asked", len(asked))
			}
			if size, ok := strings.CutPrefix(s.Text(), "blob "); ok {
				if v, err := strconv.ParseInt(size, 10, 64); err == nil && v >= 0 {
					sizes[asked[n]] = v
				}
			}
			n++
		}
		return s.Err()
	})
	if err != nil {
		return nil, fmt.Errorf("classify paths: %w", err)
	}
	if n != len(asked) {
		return nil, fmt.Errorf("classify paths: cat-file answered for %d of %d objects", n, len(asked))
	}
	return sizes, nil
}

// classifyObjectID reports whether s is a full commit id in lowercase hex,
// SHA-1 or SHA-256, so it is safe to pass to git as an argument or a
// batch line.
func classifyObjectID(s string) bool {
	if len(s) != 40 && len(s) != 64 {
		return false
	}
	for i := 0; i < len(s); i++ {
		if c := s[i]; (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}
